--Drill 26: Customer revenue contribution
--Business scenario:
--Management wants to understand how much each order item contributes to its customer's
--total revenue
with customer_item_revenue as (
    select
        order_item_id,
        customer_key,
        (units_ordered * unit_price) as item_revenue,
        sum(units_ordered * unit_price) over (
            partition by customer_key) as customer_tot_revenue
    from join_lab.fact_order_item
),
contribution_pct as (
    select
        order_item_id,
        customer_key,
        item_revenue,
        customer_tot_revenue,
        (item_revenue / nullif(
            customer_tot_revenue, 0
        )) * 100 as item_customer_contribution_pct
    from customer_item_revenue
)
select
    order_item_id,
    customer_key,
    item_revenue,
    customer_tot_revenue,
    round(item_customer_contribution_pct, 2) as item_customer_contribution_pct
from contribution_pct
    ;
--they should all sum up to 100%.


--Drill 27: Product revenue contribution
--Business scenario:
--A product manager wants to understand each order item's contribution to the total
--revenue generated by it's product
with product_item_revenue as (
    select
        order_item_id,
        product_key,
        (units_ordered * unit_price) as item_revenue,
        sum(units_ordered * unit_price) over (partition by product_key) as product_revenue
    from join_lab.fact_order_item
),
product_contribution_pct as (
    select
        order_item_id,
        product_key,
        item_revenue,
        product_revenue,
        (item_revenue / nullif(
            product_revenue, 0)) * 100 as item_product_contribution_pct
    from product_item_revenue
)
select
    order_item_id,
    product_key,
    item_revenue,
    product_revenue,
    round(item_product_contribution_pct, 2) as item_product_contribution_pct
from product_contribution_pct
    ;



--Drill 28: Customer revenue vs average
--Business scenario:
--Management wants to identify individual order items whose revenue exceeds the average
--order item revenue for their customer
with customer_item_revenues as (
    select
        order_item_id,
        customer_key,
        (units_ordered * unit_price) as item_revenue
    from join_lab.fact_order_item
),
avg_customer_revenue as (
    select
        order_item_id,
        customer_key,
        item_revenue,
        avg(item_revenue) over (partition by customer_key) as avg_revenue
    from customer_item_revenues
),
revenue_difference_tbl as (
    select
        order_item_id,
        customer_key,
        item_revenue,
        avg_revenue,
        (item_revenue - avg_revenue) as revenue_difference
    from avg_customer_revenue
),
revenue_classification as (
    select
        order_item_id,
        customer_key,
        item_revenue,
        avg_revenue,
        revenue_difference,
        case
            when revenue_difference > 0 then 'Above customer average'
            when revenue_difference < 0 then 'Below customer average'
            else 'Equal to customer average'
        end as classification
    from revenue_difference_tbl
)
select
    order_item_id,
    customer_key,
    item_revenue,
    round(avg_revenue, 2) as avg_revenue,
    round(revenue_difference, 2) as revenue_difference,
    classification
from revenue_classification
    ;


--Drill 29: Customer revenue running analysis
--Business scenario:
--A supply chain analyst wants to observe how revenue accumulates across a customer's
--order items
with customer_item_revenue as (
    select
        order_item_id,
        customer_key,
        (units_ordered * unit_price) as item_revenue,
        sum(units_ordered * unit_price) over (
            partition by customer_key) as customer_revenue,
        sum(units_ordered * unit_price) over (
            partition by customer_key order by order_item_id
        ) as customer_running_revenue
    from join_lab.fact_order_item
),
remaining_revenue as (
    select
        order_item_id,
        customer_key,
        item_revenue,
        customer_revenue,
        customer_running_revenue,
        (customer_revenue - customer_running_revenue) as customer_remaining_revenue
    from customer_item_revenue
)
select
    order_item_id,
    customer_key,
    item_revenue,
    customer_revenue,
    customer_running_revenue,
    customer_remaining_revenue
from remaining_revenue
    ;
